"""PostgreSQL compatibility boundary for the existing versioned domain services.

SQLite stays available for local regression. Production must explicitly configure
SHANGAN_DATABASE_URL; no silent fallback from a failed PostgreSQL connection.
"""
import os
import re

KEYS = {'runs':('id',), 'routes':('id',), 'agent_tool_calls':('id',),
        'team_projects':('id',), 'team_ai_runs':('id',),
        'team_session_bindings':('session_id',), 'workflows':('project',)}
_engine = None


class Record(dict):
    def __getitem__(self, key):
        return list(self.values())[key] if isinstance(key, int) else super().__getitem__(key)


def row_factory(cursor):
    names = [c.name for c in cursor.description] if cursor.description else []
    return lambda values: Record(zip(names, values))


def translate(sql):
    sql = sql.strip()
    if sql.upper().startswith('PRAGMA '):
        return 'SELECT 1'
    if sql.upper() == 'BEGIN IMMEDIATE':
        # Same lock for all legacy read/modify/write transactions across workers.
        return 'SELECT pg_advisory_xact_lock(72190411)'
    sql = re.sub(r'INTEGER PRIMARY KEY AUTOINCREMENT', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', sql, flags=re.I)
    sql = re.sub(r'\bBLOB\b', 'BYTEA', sql, flags=re.I)
    if re.search(r'\browid\b', sql, re.I):
        table = re.search(r'FROM\s+(\w+)', sql, re.I).group(1)
        order = 'session_id' if table == 'team_session_bindings' else 'id'
        sql = re.sub(r'\browid\b', order, sql, flags=re.I)
    return sql.replace('?', '%s')


class Connection:
    def __init__(self, raw):
        self.raw = raw

    def execute(self, sql, params=()):
        replace = re.match(r'INSERT OR REPLACE INTO\s+(\w+)\s+VALUES', sql.strip(), re.I)
        if replace:
            table = replace.group(1)
            if table not in KEYS:
                raise ValueError('Unsupported upsert table: '+table)
            columns = [r['column_name'] for r in self.raw.execute(
                'SELECT column_name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=%s ORDER BY ordinal_position', (table,))]
            sql = re.sub(r'INSERT OR REPLACE', 'INSERT', sql, flags=re.I)
            update = ','.join(f'{c}=excluded.{c}' for c in columns if c not in KEYS[table])
            sql += ' ON CONFLICT('+','.join(KEYS[table])+') DO UPDATE SET '+update
        return self.raw.execute(translate(sql), params)

    def executescript(self, script):
        for statement in script.split(';'):
            if statement.strip():
                self.execute(statement)

    def __enter__(self):
        return self

    def __exit__(self, kind, value, traceback):
        try:
            self.raw.rollback() if kind else self.raw.commit()
        finally:
            self.close()

    def close(self):
        self.raw.close()

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()


def connect():
    global _engine
    from sqlalchemy import create_engine
    if _engine is None:
        url = os.environ['SHANGAN_DATABASE_URL'].replace('postgres://', 'postgresql://', 1)
        if url.startswith('postgresql://'):
            url = url.replace('postgresql://', 'postgresql+psycopg://', 1)
        if not url.startswith('postgresql+psycopg://'):
            raise ValueError('Shared backend requires PostgreSQL')
        _engine = create_engine(url, pool_pre_ping=True, pool_size=5, max_overflow=5,
                                connect_args={'connect_timeout':5, 'options':'-c statement_timeout=30000'})
    raw = _engine.raw_connection()
    raw.driver_connection.row_factory = row_factory
    return Connection(raw)
